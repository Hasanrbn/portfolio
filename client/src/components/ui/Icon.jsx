/**
 * Decorative inline SVG icon. It is hidden from screen readers, so the control that
 * contains it must have its own text or aria-label. Add more icons to ICON_PATHS as needed.
 */
export default function Icon({ name, size = 20 }) {
  const shape = ICON_PATHS[name];
  if (!shape) {
    throw new Error(`Unknown icon "${name}"`);
  }

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {shape}
    </svg>
  );
}
